using System.Linq;
using System.Numerics;
using Content.Client._Starlight.Lobby.UI;
using Content.Client._Starlight.TextToSpeech;
using Content.Shared._LP.VoiceMask;
using Content.Shared._Starlight.TextToSpeech;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._LP.VoiceMask;

/// <summary>
/// Выбор голоса TTS в окне голосовой маски. Список голосов тот же, что при создании персонажа.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class VoiceMaskVoiceSelector : BoxContainer
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IEntityManager _entMan = default!;

    private DefaultWindow? _window;
    private VoicePicker? _picker;
    private string? _voice;

    public event Action<string?>? OnVoiceChange;

    public VoiceMaskVoiceSelector()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        VoiceButton.OnPressed += _ => OpenWindow();
        ResetButton.OnPressed += _ => OnVoiceChange?.Invoke(null);
        UpdateButton();
    }

    public void SetVoice(string? voice)
    {
        _voice = voice;
        UpdateButton();

        _picker?.Select(voice);
    }

    private void OpenWindow()
    {
        if (_window == null)
        {
            var voices = _prototype.EnumeratePrototypes<VoicePrototype>()
                .Where(VoiceMaskTtsVoices.IsAllowed)
                .ToList();

            _picker = new VoicePicker(voices, _prototype);
            _picker.OnVoiceSelected += voice => OnVoiceChange?.Invoke(voice.ID);
            _picker.OnPreviewRequested += voice => _entMan.System<TextToSpeechSystem>().RequestPreviewTts(voice.ID);
            _picker.Select(_voice);

            _window = new DefaultWindow
            {
                Title = Loc.GetString("voice-selector-title"),
                MinSize = new Vector2(450, 500),
                SetSize = new Vector2(550, 650),
            };
            _window.Contents.AddChild(_picker);
        }

        _window.OpenCentered();
    }

    private void UpdateButton() => VoiceButton.Text = _voice != null && _prototype.TryIndex<VoicePrototype>(_voice, out var proto)
            ? Loc.GetString(proto.Name)
            : Loc.GetString("voice-mask-name-change-tts-voice-default");

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _window?.Close();
        _window = null;
        _picker = null;
    }
}
